@bp.get("/opportunities")
def list_opportunities():
    opp_type = (request.args.get("type") or "").strip().lower()
    field = (request.args.get("field") or "").strip().lower()
    mode = (request.args.get("mode") or "").strip().lower()
    query = (request.args.get("q") or "").strip().lower()

    filtered = OPPORTUNITIES
    if opp_type and opp_type != "all":
        filtered = [o for o in filtered if o["type"].lower() == opp_type]
    if field and field != "all":
        filtered = [o for o in filtered if o["field"].lower() == field]
    if mode and mode != "all":
        filtered = [o for o in filtered if o["mode"].lower() == mode]
    if query:
        filtered = [
            o for o in filtered
            if query in o["title"].lower()
            or query in o["organization"].lower()
            or query in o["description"].lower()
            or any(query in t.lower() for t in o["tags"])
        ]

    return jsonify({"opportunities": filtered, "total": len(filtered)})
